import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.SART_PLAYWRIGHT || (process.env.HOME+'/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const root=path.resolve(import.meta.dirname,'..');
const output=path.join(root,'.local/qa');fs.mkdirSync(output,{recursive:true});
const base=process.env.SART_TEST_URL || 'http://127.0.0.1:8768';
const checks=[];const errors=[];
function check(name,condition){if(!condition)throw new Error(name);checks.push({name,passed:true});console.log('PASS '+name);}
const browser=await chromium.launch({headless:true,executablePath:process.env.SART_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:1920,height:1080},deviceScaleFactor:1});
const tv=await context.newPage();tv.on('pageerror',e=>errors.push(e.message));
let mac;
try{
  await tv.goto(base+'/preview/');
  await tv.waitForSelector('.collection-card');
  check('four bundled collection covers open',await tv.locator('.collection-card').count()===4);
  await tv.locator('[data-action="open-collection"][data-id="light-water"]').click();
  check('included collection contains 15 artworks',await tv.locator('.art-card').count()===15);
  await tv.waitForFunction(()=>[...document.querySelectorAll('.art-card img')].every(i=>i.complete&&i.naturalWidth>0));
  check('gallery has no horizontal overflow',await tv.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await tv.screenshot({path:path.join(output,'gallery-1920.png'),fullPage:true});
  await tv.locator('.art-card').first().focus();
  const firstFocus=await tv.evaluate(()=>document.activeElement.dataset.focus);
  await tv.keyboard.press('ArrowRight');
  check('D-pad moves between artwork cards',(await tv.evaluate(()=>document.activeElement.dataset.focus))!==firstFocus);
  await tv.keyboard.press('Enter');await tv.waitForSelector('.player');
  check('OK opens artwork without persistent controls',!(await tv.locator('.player-controls').getAttribute('class')).includes('shown'));
  await tv.keyboard.press('Enter');await tv.locator('[data-action="mat"]').click();
  await tv.locator('[data-look-tab="mat"]').click();
  await tv.locator('[data-matte="white"]').click();
  await tv.locator('[data-look-tab="fit"]').click();
  await tv.locator('[data-fit="contain"]').click();
  await tv.waitForFunction(()=>document.querySelector('.canvas').style.getPropertyValue('--fit')==='contain');
  check('mat and fit update the artwork',await tv.locator('.canvas').evaluate(el=>el.style.getPropertyValue('--matte')==='#faf9f5'));
  await tv.keyboard.press('ArrowDown');
  check('D-pad moves directly from image fit to Done',await tv.locator('[data-focus="mat-done"]').evaluate(el=>el===document.activeElement));
  await tv.keyboard.press('ArrowUp');await tv.keyboard.press('ArrowLeft');await tv.keyboard.press('Enter');
  await tv.waitForFunction(()=>document.querySelector('.canvas').style.getPropertyValue('--fit')==='cover');
  check('D-pad can switch back to Fill space',await tv.locator('[data-fit="cover"]').getAttribute('aria-pressed')==='true');
  await tv.screenshot({path:path.join(output,'mat-controls.png'),fullPage:true});
  await tv.keyboard.press('ArrowDown');await tv.keyboard.press('Enter');
  check('Done dismisses Mat and fit with the remote',await tv.locator('#dialog').evaluate(el=>!el.open));
  await tv.locator('[data-action="favourite"]').click();
  await tv.waitForFunction(()=>document.querySelector('[data-action="favourite"]')?.getAttribute('aria-pressed')==='true');
  check('artwork can be favourited',await tv.locator('[data-action="favourite"]').getAttribute('aria-pressed')==='true');
  await tv.keyboard.press('Escape');await tv.keyboard.press('Escape');
  await tv.locator('[data-tab="favourites"]').click();
  check('favourites filter displays the selected piece',await tv.locator('.art-card').count()===1);
  await tv.locator('[data-tab="settings"]').click();
  await tv.locator('[data-focus="tab-settings"]').focus();
  for(let step=0;step<6;step++)await tv.keyboard.press('ArrowDown');
  check('Down navigation reaches the PC connection action',await tv.locator('[data-focus="library-pair"]').evaluate(el=>el===document.activeElement));
  check('Settings has no duplicate focus identifiers',await tv.locator('#app [data-focus]').evaluateAll(els=>new Set(els.map(el=>el.dataset.focus)).size===els.length));
  await tv.locator('[data-focus="setting-interval"]').click();
  await tv.locator('[data-focus="choice-interval-0"]').click();
  await tv.locator('[data-action="toggle-resume"]').click();
  await tv.locator('[data-action="start-slideshow"]').click();
  const initialSrc=await tv.locator('.canvas img').getAttribute('src');
  await tv.waitForFunction(src=>document.querySelector('.canvas img')?.getAttribute('src')!==src,initialSrc,{timeout:40000});
  check('slideshow advances after the selected real-time interval',true);
  await tv.keyboard.press('Escape');
  await tv.locator('[data-tab="gallery"]').click();
  mac=await context.newPage();mac.on('pageerror',e=>errors.push(e.message));
  await mac.goto(base+'/');
  await mac.locator('#photos').setInputFiles({name:'SART upload proof.jpg',mimeType:'image/jpeg',buffer:fs.readFileSync(path.join(root,'app/assets/16568.jpg'))});
  await mac.waitForFunction(()=>document.querySelector('#upload-status').textContent.includes('1 photo ready'));
  check('Mac upload page processes an actual photo',await mac.locator('.photo').count()===1);
  await mac.screenshot({path:path.join(output,'mac-upload-desktop.png'),fullPage:true});
  const status=await (await fetch(base+'/api/manage/status')).json();
  await tv.bringToFront();await tv.locator('[data-action="pair"]').click();
  await tv.locator('#mac-address').fill(base);await tv.locator('#pair-code').fill(status.code);
  await tv.locator('#pair-submit').click();
  await tv.locator('[data-action="open-collection"][data-id="my-photos"]').click();
  await tv.getByRole('button',{name:'Display SART upload proof',exact:true}).waitFor();
  check('TV pairs and saves the uploaded image in My photos',await tv.locator('.art-card').count()===1);
  await tv.getByRole('button',{name:'Display SART upload proof',exact:true}).click();
  await tv.waitForFunction(()=>document.querySelector('.canvas img')?.naturalWidth>0);
  check('saved artwork displays from a local Blob',(await tv.locator('.canvas img').getAttribute('src')).startsWith('blob:'));
  await tv.route('**/api/**',route=>route.abort());
  await tv.reload();await tv.waitForSelector('.player');
  await tv.waitForFunction(()=>document.querySelector('.canvas img')?.naturalWidth>0);
  check('saved photo and resume preference survive reload with library network blocked',await tv.locator('.canvas img').getAttribute('alt')==='SART upload proof');
  await tv.screenshot({path:path.join(output,'offline-artwork.png'),fullPage:true});
  await tv.keyboard.press('Enter');await tv.locator('[data-action="remove"]').click();await tv.locator('[data-action="confirm-remove"]').click();
  await tv.waitForSelector('.collections-grid');
  await tv.unroute('**/api/**');
  await tv.locator('[data-tab="settings"]').click();await tv.locator('[data-action="sync"]').click();
  await tv.waitForFunction(()=>document.querySelector('#toast').textContent==='Your gallery is up to date.');
  await tv.locator('[data-tab="gallery"]').click();
  check('removed TV photo is not silently reimported by sync',await tv.locator('[data-action="open-collection"][data-id="my-photos"]').count()===0);
  await tv.locator('[data-tab="settings"]').click();
  check('Settings omits obsolete restore action and its remote focus target',await tv.locator('[data-action="restore-removed"], [data-focus="restore-removed"], [data-nav-up="restore-removed"], [data-nav-down="restore-removed"]').count()===0);
  check('Removed companion photos remain excluded',await tv.locator('.library-stat strong').textContent()==='0');
  await tv.locator('[data-tab="gallery"]').click();
  await tv.setViewportSize({width:1280,height:720});await tv.screenshot({path:path.join(output,'gallery-1280.png'),fullPage:true});
  check('TV gallery fits a 1280px viewport',await tv.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mac.bringToFront();await mac.setViewportSize({width:390,height:844});await mac.screenshot({path:path.join(output,'upload-mobile.png'),fullPage:true});
  check('upload page fits a phone-width viewport',await mac.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('no uncaught browser errors',errors.length===0);
  fs.writeFileSync(path.join(output,'browser-results.json'),JSON.stringify({status:'passed',checks,errors,limitations:['Browser verification does not establish Samsung TV runtime behaviour.','Offline test blocked the library API while the preview app assets remained locally served.']},null,2)+'\n');
}catch(error){
  await tv.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});
  fs.writeFileSync(path.join(output,'browser-results.json'),JSON.stringify({status:'failed',checks,errors,error:String(error)},null,2)+'\n');
  throw error;
}finally{
  const status=await(await fetch(base+'/api/manage/status')).json().catch(()=>({items:[]}));
  for(const item of status.items)await fetch(base+'/api/manage/photos/'+item.id,{method:'DELETE'});
  await fetch(base+'/api/manage/pairings',{method:'DELETE'});
  await context.close();await browser.close();
}
